# Loaded by update-recovery.ps1: reuse its path checks, scoped profile backups,
# atomic journal publication, progress reporting and legacy recovery unchanged.
$deltaManifestName = 'resources\update-manifest.json'
$deltaMetadataNames = @($deltaManifestName, 'Uninstall Lira.exe', 'uninstallerIcon.ico')

function Assert-DeltaName([string]$Name) {
  if ([string]::IsNullOrWhiteSpace($Name) -or $Name.Contains('/') -or $Name -match '[<>:"|?*\x00-\x1f]' -or [IO.Path]::IsPathRooted($Name)) { throw 'Invalid update entry.' }
  foreach ($part in $Name.Split('\')) {
    if ($part -in @('', '.', '..') -or $part.EndsWith('.') -or $part.EndsWith(' ') -or
        $part -match '^(?i:CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\.|$)') { throw 'Invalid update entry.' }
  }
}

function Get-DeltaPath([string]$Root, [string]$Name) {
  Assert-DeltaName $Name
  $file = Get-SnapshotChild $Root $Name
  Assert-RegularPath $file
  return $file
}

function Assert-DeltaFiles($Files) {
  $seen = @{}
  foreach ($file in @($Files)) {
    Assert-DeltaName $file.Name
    if ($seen.ContainsKey($file.Name) -or $file.Length -isnot [ValueType] -or $file.Length -lt 0 -or
        [string]$file.Hash -notmatch '^[a-fA-F0-9]{64}$') { throw 'Invalid update file descriptor.' }
    $seen[$file.Name] = $true
  }
  foreach ($name in $seen.Keys) {
    $parentName = [IO.Path]::GetDirectoryName($name)
    while ($parentName) {
      if ($seen.ContainsKey($parentName)) { throw 'Overlapping update entries.' }
      $parentName = [IO.Path]::GetDirectoryName($parentName)
    }
  }
}

function Read-DeltaManifest([string]$Root) {
  $file = Get-DeltaPath $Root $deltaManifestName
  $manifest = Get-Content -LiteralPath $file -Raw -Encoding UTF8 | ConvertFrom-Json
  if ($manifest.FormatVersion -ne 1 -or [string]::IsNullOrWhiteSpace($manifest.Version) -or @($manifest.Files).Count -eq 0) { throw 'Invalid application manifest.' }
  Assert-DeltaFiles $manifest.Files
  foreach ($name in $deltaMetadataNames) {
    if (@($manifest.Files | Where-Object { $_.Name -eq $name }).Count) { throw 'Installer metadata must not occur in the package file list.' }
  }
  foreach ($required in @('Lira.exe', 'resources\app.asar')) {
    if (@($manifest.Files | Where-Object { $_.Name -eq $required }).Count -ne 1) { throw 'Missing application entry point.' }
  }
  return $manifest
}

function Get-DeltaDescriptor([string]$Root, [string]$Name) {
  $file = Get-DeltaPath $Root $Name
  $item = Get-Item -LiteralPath $file -Force
  if ($item.PSIsContainer) { throw 'An update file is a directory.' }
  return [pscustomobject]@{ Name = $Name; Length = $item.Length; Hash = [LiraUpdateIO]::HashFile($file, [Action]{ Report-Progress }) }
}

function Assert-DeltaFile([string]$Root, $File) {
  $actual = Get-DeltaDescriptor $Root $File.Name
  if ($actual.Length -ne $File.Length -or $actual.Hash -ne $File.Hash) { throw "Update file integrity mismatch: $($File.Name)" }
}

function Get-DeltaPayload([string]$Root) {
  $Root = Get-ManagedPath $Root
  foreach ($managed in $managedTrees) {
    if ($Root -eq $managed -or $Root.StartsWith($managed + '\', [StringComparison]::OrdinalIgnoreCase) -or
        $managed.StartsWith($Root + '\', [StringComparison]::OrdinalIgnoreCase)) { throw 'Payload overlaps managed update directories.' }
  }
  Assert-RegularTree $Root
  $manifest = Read-DeltaManifest $Root
  foreach ($file in $manifest.Files) { Assert-DeltaFile $Root $file }
  $files = @($manifest.Files) + @(Get-DeltaDescriptor $Root $deltaManifestName)
  # The uninstaller is generated by NSIS after packaging, so it is managed as
  # installer metadata rather than participating in the self-contained manifest.
  $files += Get-DeltaDescriptor $Root 'Uninstall Lira.exe'
  if (Test-Path -LiteralPath (Join-Path $Root 'uninstallerIcon.ico')) { $files += Get-DeltaDescriptor $Root 'uninstallerIcon.ico' }
  Assert-DeltaFiles $files
  return [pscustomobject]@{ Manifest = $manifest; Files = $files }
}

function Assert-DeltaTarget([string]$Name) {
  $target = Get-DeltaPath $installPath $Name
  if (Test-Path -LiteralPath $target -PathType Container) { throw 'An application file was replaced by a directory.' }
  $parentPath = [IO.Directory]::GetParent($target).FullName
  while ($parentPath -ne $installPath) {
    Assert-RegularPath $parentPath
    if (Test-Path -LiteralPath $parentPath -PathType Leaf) { throw 'An application parent is a file.' }
    $parentPath = [IO.Directory]::GetParent($parentPath).FullName
  }
}

function Write-DeltaSnapshot($Snapshot, [string]$Directory) {
  $file = Join-Path $Directory 'snapshot.json'
  Assert-RegularPath $file
  Assert-RegularPath "$file.tmp"
  [LiraUpdateIO]::WriteDurableText("$file.tmp", ($Snapshot | ConvertTo-Json -Depth 12))
  [LiraUpdateIO]::PublishFile("$file.tmp", $file)
}

function Assert-DeltaSnapshot($Snapshot, [string]$Directory) {
  Assert-ManifestIdentity $Snapshot
  if ($Snapshot.Application.Storage -ne 'delta' -or -not $Snapshot.Application.Existed) { throw 'Invalid differential backup.' }
  Assert-RegularTree $Directory
  Assert-DeltaFiles $Snapshot.Application.Files
  Assert-DeltaFiles $Snapshot.NewFiles
  Assert-DeltaFiles $Snapshot.PreviousFiles
  $oldFiles = @{}; foreach ($file in $Snapshot.Application.Files) { $oldFiles[$file.Name] = $file }
  $incoming = @{}; foreach ($file in $Snapshot.NewFiles) { $incoming[$file.Name] = $file }
  $previous = @{}; foreach ($file in $Snapshot.PreviousFiles) { $previous[$file.Name] = $true }
  $seen = @{}
  foreach ($op in $Snapshot.Operations) {
    Assert-DeltaTarget $op.Name
    if ($seen.ContainsKey($op.Name) -or $op.Kind -notin @('Add', 'Replace', 'Remove') -or $op.Existed -isnot [bool]) { throw 'Invalid differential operation.' }
    $seen[$op.Name] = $true
    if ($op.Kind -eq 'Remove') {
      if (-not $previous.ContainsKey($op.Name) -or $incoming.ContainsKey($op.Name)) { throw 'Removal outside the previous application manifest.' }
    } elseif (-not $incoming.ContainsKey($op.Name)) { throw 'Write outside incoming manifest.' }
    if ($op.Existed -ne ($op.Kind -ne 'Add') -or $oldFiles.ContainsKey($op.Name) -ne $op.Existed) { throw 'Incomplete differential backup.' }
  }
  if ($oldFiles.Count -ne @($Snapshot.Operations | Where-Object { $_.Existed }).Count) { throw 'Unexpected differential backup entries.' }
  foreach ($directoryName in $Snapshot.CreatedDirectories) {
    Assert-DeltaName $directoryName
    $children = @($Snapshot.Operations | Where-Object { $_.Kind -ne 'Remove' -and $_.Name.StartsWith($directoryName + '\', [StringComparison]::OrdinalIgnoreCase) })
    if ($children.Count -eq 0) { throw 'Directory outside differential changes.' }
    $null = Get-DeltaPath $installPath $directoryName
  }
  Assert-TreeSnapshot $Snapshot.Application (Join-Path $Directory 'app')
  $names = @{}
  foreach ($profile in $Snapshot.Profiles) {
    $null = Get-ProfilePath $profile.Name
    if ($names.ContainsKey($profile.Name)) { throw 'Duplicate profile snapshot.' }
    $names[$profile.Name] = $true
    Assert-ProfileChanges $profile
    $source = Join-Path (Join-Path $Directory 'user-data') $profile.Name
    Assert-RegularTree $source
    Assert-TreeSnapshot $profile $source
  }
  if (-not $names.ContainsKey($profileName)) { throw 'Missing primary profile snapshot.' }
}

function Assert-DeltaSpace([string]$Directory, [long]$Bytes) {
  $driveName = [IO.Path]::GetPathRoot($Directory).TrimEnd(':', '\')
  $drive = Get-PSDrive -Name $driveName -PSProvider FileSystem -ErrorAction Stop
  if ($null -eq $drive.Free -or $drive.Free -lt $Bytes) { throw 'Insufficient free space for a recoverable update.' }
}

function Backup-Delta([string]$PayloadRoot) {
  if (Test-Path -LiteralPath $pendingPath) { throw 'An unfinished update must be recovered first.' }
  $incoming = Get-DeltaPayload $PayloadRoot
  $previous = Read-DeltaManifest $installPath
  $old = @{}; foreach ($file in $previous.Files) { $old[$file.Name] = $file }
  foreach ($name in $deltaMetadataNames) {
    $target = Get-DeltaPath $installPath $name
    if (Test-Path -LiteralPath $target -PathType Leaf) { $old[$name] = Get-DeltaDescriptor $installPath $name }
  }
  $next = @{}; foreach ($file in $incoming.Files) { $next[$file.Name] = $file }
  $operations = @(); $backupFiles = @(); $created = @{}; $kept = 0
  foreach ($file in $incoming.Files) {
    Assert-DeltaTarget $file.Name
    $target = Get-DeltaPath $installPath $file.Name
    $exists = Test-Path -LiteralPath $target -PathType Leaf
    $actual = if ($exists) { Get-DeltaDescriptor $installPath $file.Name } else { $null }
    if ($exists -and $actual.Length -eq $file.Length -and $actual.Hash -eq $file.Hash) { $kept++; continue }
    if ($exists -and -not $old.ContainsKey($file.Name)) { throw "Incoming file conflicts with an unmanaged file: $($file.Name)" }
    $operations += [pscustomobject]@{ Name = $file.Name; Kind = $(if ($exists) { 'Replace' } else { 'Add' }); Existed = [bool]$exists }
    if ($exists) { $backupFiles += $actual }
    $parentName = [IO.Path]::GetDirectoryName($file.Name)
    while ($parentName) {
      if (-not (Test-Path -LiteralPath (Get-DeltaPath $installPath $parentName))) { $created[$parentName] = $true }
      $parentName = [IO.Path]::GetDirectoryName($parentName)
    }
  }
  foreach ($name in $old.Keys) {
    if ($next.ContainsKey($name)) { continue }
    Assert-DeltaTarget $name
    if (-not (Test-Path -LiteralPath (Get-DeltaPath $installPath $name))) { continue }
    $operations += [pscustomobject]@{ Name = $name; Kind = 'Remove'; Existed = $true }
    $backupFiles += Get-DeltaDescriptor $installPath $name
  }
  $profileNames = @($profileName)
  if (Test-Path -LiteralPath $profileParent) {
    $profileNames += @(Get-ChildItem -LiteralPath $profileParent -Directory -Force | Where-Object { $_.Name.StartsWith("$profileName-inst-", [StringComparison]::OrdinalIgnoreCase) } | ForEach-Object { $_.Name })
  }
  $profiles = @(foreach ($name in $profileNames) { Get-ProfileChangesSnapshot $name })
  $backupBytes = 0L; foreach ($file in $backupFiles) { $backupBytes += $file.Length }
  $profileBytes = 0L; foreach ($profile in $profiles) { foreach ($file in $profile.Files) { $profileBytes += $file.Length } }
  $writeBytes = 0L; foreach ($op in $operations | Where-Object { $_.Kind -ne 'Remove' }) { $writeBytes += $next[$op.Name].Length }
  Assert-DeltaSpace $installPath ($backupBytes + 2 * $profileBytes + $writeBytes + 1MB)
  if ([IO.Path]::GetPathRoot($userDataPath) -ne [IO.Path]::GetPathRoot($installPath)) { Assert-DeltaSpace $userDataPath ($profileBytes + 1MB) }
  $snapshot = [pscustomobject]@{
    FormatVersion = 6; TransactionId = [Guid]::NewGuid().ToString(); InstallDir = $installPath; UserDataDir = $userDataPath
    Application = [pscustomobject]@{ Existed = $true; Storage = 'delta'; Files = $backupFiles; Directories = @() }
    Profiles = $profiles; Operations = $operations; NewFiles = $incoming.Files; PreviousFiles = @($old.Values); CreatedDirectories = @($created.Keys)
    Stats = [pscustomobject]@{ FilesKept = $kept; FilesChanged = $operations.Count; BackupBytes = $backupBytes; ApplyBytes = $writeBytes; WrittenBytes = 0L }
  }
  $script:deltaStats = $snapshot.Stats
  Remove-UpdateTree $stagingPath
  $null = [IO.Directory]::CreateDirectory($stagingPath)
  Write-DeltaSnapshot $snapshot $stagingPath
  $journal = [pscustomobject]@{ FormatVersion = 6; TransactionId = $snapshot.TransactionId; InstallDir = $installPath; UserDataDir = $userDataPath; BackupDir = $stagingPath; Phase = 'Preparing'; Completed = @(); WrittenBytes = 0L }
  Write-Pending $journal
  $script:totalFiles = $backupFiles.Count; $script:totalBytes = $backupBytes + $profileBytes
  foreach ($profile in $profiles) { $script:totalFiles += @($profile.Files).Count }
  Copy-SnapshotTree $snapshot.Application $installPath (Join-Path $stagingPath 'app') 'Copiando alteracoes'
  foreach ($profile in $profiles) { Copy-SnapshotTree $profile (Get-ProfilePath $profile.Name) (Join-Path (Join-Path $stagingPath 'user-data') $profile.Name) }
  Write-DeltaSnapshot $snapshot $stagingPath
  Assert-DeltaSnapshot $snapshot $stagingPath
  $journal.Phase = 'Prepared'; Write-Pending $journal
  # The previous backup is retained until the new one is complete and verified.
  Remove-UpdateTree $backupPath
  Move-UpdateTree $stagingPath $backupPath
  $journal.BackupDir = $backupPath; $journal.Phase = 'Installing'
  Write-Pending $journal
  Report-Progress 'Backup diferencial pronto' $true
}

function Publish-DeltaFile([string]$SourceRoot, $File, [string]$TransactionId, [bool]$CreateOnly = $false) {
  $source = Get-DeltaPath $SourceRoot $File.Name
  $target = Get-DeltaPath $installPath $File.Name
  $temporary = "$target.lira-new-$TransactionId"
  Assert-RegularPath $temporary
  $null = [IO.Directory]::CreateDirectory([IO.Directory]::GetParent($target).FullName)
  try {
    if (Test-Path -LiteralPath $temporary) { Remove-Item -LiteralPath $temporary -Force }
    $hash = [LiraUpdateIO]::CopyAndHash($source, $temporary, $File.Length, [Action]{ Report-Progress })
    if ($hash -ne $File.Hash) { throw 'Source changed during update publication.' }
    if ($CreateOnly) { [IO.File]::Move($temporary, $target) }
    else { [LiraUpdateIO]::PublishFile($temporary, $target) }
    Assert-DeltaFile $installPath $File
  } finally {
    Assert-RegularPath $temporary
    if (Test-Path -LiteralPath $temporary -PathType Leaf) { Remove-Item -LiteralPath $temporary -Force }
  }
}

function Apply-Delta([string]$PayloadRoot) {
  $recovery = Read-Recovery
  $snapshot = $recovery.Snapshot; $journal = $recovery.Journal
  if ($snapshot.FormatVersion -ne 6 -or $journal.Phase -ne 'Installing') { throw 'The update is not ready to apply.' }
  $script:deltaStats = $snapshot.Stats
  Assert-DeltaSnapshot $snapshot $recovery.Directory
  $incoming = Get-DeltaPayload $PayloadRoot
  $files = @{}; foreach ($file in $incoming.Files) { $files[$file.Name] = $file }
  if ($files.Count -ne @($snapshot.NewFiles).Count) { throw 'Payload changed after preparation.' }
  foreach ($file in $snapshot.NewFiles) {
    if (-not $files.ContainsKey($file.Name) -or $file.Hash -ne $files[$file.Name].Hash -or $file.Length -ne $files[$file.Name].Length) { throw 'Payload changed after preparation.' }
  }
  $previous = @{}; foreach ($file in $snapshot.Application.Files) { $previous[$file.Name] = $file }
  $journal.Phase = 'Applying'; Write-Pending $journal
  foreach ($op in $snapshot.Operations | Sort-Object { $_.Name -eq $deltaManifestName }) {
    $target = Get-DeltaPath $installPath $op.Name
    if ($op.Existed) { Assert-DeltaFile $installPath $previous[$op.Name] }
    elseif (Test-Path -LiteralPath $target) { throw 'A new application path appeared after preparation.' }
    if ($op.Kind -eq 'Remove') { Remove-Item -LiteralPath $target -Force }
    else {
      Publish-DeltaFile $PayloadRoot $files[$op.Name] $snapshot.TransactionId ($op.Kind -eq 'Add')
      $journal.WrittenBytes += $files[$op.Name].Length
      $script:deltaStats.WrittenBytes = $journal.WrittenBytes
    }
    $journal.Completed = @($journal.Completed) + $op.Name
    Write-Pending $journal
    Report-Progress 'Aplicando alteracoes' $true
  }
  foreach ($file in $snapshot.NewFiles) { Assert-DeltaFile $installPath $file }
  $journal.Phase = 'Applied'; Write-Pending $journal
}

function Restore-Delta($Recovery) {
  $snapshot = $Recovery.Snapshot
  if ($Recovery.Preparing) {
    # No application or live profile writes occur during preparation.
    if ($Recovery.Directory -eq $stagingPath) { Remove-UpdateTree $stagingPath }
    Remove-Item -LiteralPath $pendingPath -Force
    return
  }
  Assert-DeltaSnapshot $snapshot $Recovery.Directory
  if ($Recovery.Directory -eq $stagingPath) {
    Remove-UpdateTree $backupPath
    Move-UpdateTree $stagingPath $backupPath
    $Recovery.Directory = $backupPath
    $Recovery.Journal.BackupDir = $backupPath
    Write-Pending $Recovery.Journal
  }
  if ($Recovery.Journal.Phase -in @('Installing', 'Prepared')) {
    # No live application/profile writes have started. Do not overwrite edits
    # made outside the updater while the verified backup was being prepared.
    Remove-Item -LiteralPath $pendingPath -Force
    return
  }
  Remove-UpdateTree $profileStagingPath
  foreach ($profile in $snapshot.Profiles) {
    Assert-ProfileChangeTargets $profile
    Copy-SnapshotTree $profile (Join-Path (Join-Path $Recovery.Directory 'user-data') $profile.Name) (Join-Path $profileStagingPath $profile.Name) 'Restaurando saves'
  }
  $Recovery.Journal.Phase = 'Restoring'; Write-Pending $Recovery.Journal
  foreach ($op in $snapshot.Operations) {
    $target = Get-DeltaPath $installPath $op.Name
    $temporary = "$target.lira-new-$($snapshot.TransactionId)"
    Assert-RegularPath $temporary
    if (Test-Path -LiteralPath $temporary -PathType Leaf) { Remove-Item -LiteralPath $temporary -Force }
    if ($op.Kind -eq 'Add' -and (Test-Path -LiteralPath $target)) {
      $expected = @($snapshot.NewFiles | Where-Object { $_.Name -eq $op.Name })[0]
      $actual = Get-DeltaDescriptor $installPath $op.Name
      # Completed is durable after publication. Hash matching also recognizes a
      # crash after atomic replacement but before the journal was advanced.
      if ($Recovery.Journal.Completed -contains $op.Name -or ($actual.Hash -eq $expected.Hash -and $actual.Length -eq $expected.Length)) {
        Remove-Item -LiteralPath $target -Force
      }
    }
  }
  foreach ($file in $snapshot.Application.Files | Sort-Object { $_.Name -eq $deltaManifestName }) {
    Publish-DeltaFile (Join-Path $Recovery.Directory 'app') $file $snapshot.TransactionId
  }
  foreach ($profile in $snapshot.Profiles) { Restore-ProfileChanges $profile (Get-SnapshotChild $profileStagingPath $profile.Name) }
  foreach ($name in $snapshot.CreatedDirectories | Sort-Object Length -Descending) {
    $directory = Get-DeltaPath $installPath $name
    if ((Test-Path -LiteralPath $directory -PathType Container) -and @(Get-ChildItem -LiteralPath $directory -Force).Count -eq 0) { [IO.Directory]::Delete($directory, $false) }
  }
  Remove-UpdateTree $profileStagingPath
  Remove-Item -LiteralPath $pendingPath -Force
  Report-Progress 'Lira restaurado' $true
}
