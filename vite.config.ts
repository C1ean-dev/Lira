import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import electron from 'vite-plugin-electron'
import renderer from 'vite-plugin-electron-renderer'
import path from 'path'
import fs from 'fs'

const pkg = JSON.parse(fs.readFileSync(path.resolve(__dirname, './package.json'), 'utf-8'))

// Stage the RNNoise WASM bytes as a tracked TS module (base64) so the audio
// worklet can be assembled at runtime from a Blob with ZERO fetches — this
// works under both vite dev (http) and the built Electron app (file://,
// where absolute fetch URLs fail and RNNoise silently never started).
// Regenerated idempotently on every dev/build from node_modules.
const rnnoiseWasmSrc = path.resolve(
  __dirname,
  'node_modules/@jitsi/rnnoise-wasm/dist/rnnoise.wasm'
)
const rnnoiseBytesDest = path.resolve(__dirname, 'src/generated/rnnoiseWasmBytes.ts')
try {
  fs.mkdirSync(path.dirname(rnnoiseBytesDest), { recursive: true })
  const wasmBytes = fs.readFileSync(rnnoiseWasmSrc)
  const prev = fs.existsSync(rnnoiseBytesDest) ? fs.readFileSync(rnnoiseBytesDest, 'utf-8') : ''
  const next =
    `// AUTO-GENERATED by vite.config.ts from node_modules/@jitsi/rnnoise-wasm — do not edit.\n` +
    `export const RNNOISE_WASM_BASE64: string =\n  '${wasmBytes.toString('base64')}'\n`
  if (prev !== next) {
    fs.writeFileSync(rnnoiseBytesDest, next, 'utf-8')
    console.log('[vite] staged RNNoise WASM bytes:', wasmBytes.length, 'bytes')
  }
} catch (e) {
  console.warn('[vite] could not stage rnnoise wasm bytes:', e instanceof Error ? e.message : e)
}

// https://vitejs.dev/config/
export default defineConfig({
  define: {
    __APP_VERSION__: JSON.stringify(pkg.version || '1.0.0'),
  },
  plugins: [
    react(),
    electron([
      {
        entry: 'electron/main.ts',
      },
      {
        entry: 'electron/preload.ts',
        onstart(options) {
          options.reload()
        },
        vite: {
          build: {
            lib: {
              entry: 'electron/preload.ts',
              formats: ['cjs'],
              fileName: () => 'preload.js',
            },
          },
        },
      },
    ]),
    renderer(),
    {
      name: 'disk-file-persistence-middleware',
      configureServer(server) {
        server.middlewares.use(async (req, res, next) => {
          if (req.url === '/api/save-asset-file' && req.method === 'POST') {
            let body = ''
            req.on('data', (chunk) => {
              body += chunk
            })
            req.on('end', () => {
              try {
                const { relativePath, content, encoding } = JSON.parse(body)
                const targetPath = path.resolve(process.cwd(), relativePath)
                fs.mkdirSync(path.dirname(targetPath), { recursive: true })
                if (encoding === 'base64') {
                  const base64Data = content.replace(/^data:image\/\w+;base64,/, '')
                  fs.writeFileSync(targetPath, Buffer.from(base64Data, 'base64'))
                } else {
                  fs.writeFileSync(targetPath, content, 'utf-8')
                }
                console.log('[DiskMiddleware] Saved asset to disk:', targetPath)
                res.setHeader('Content-Type', 'application/json')
                res.statusCode = 200
                res.end(JSON.stringify({ success: true, path: targetPath }))
              } catch (e) {
                console.error('[DiskMiddleware] Error saving asset:', e)
                res.statusCode = 500
                res.end(JSON.stringify({ error: String(e) }))
              }
            })
            return
          }
          if (req.url === '/api/save-native-assets' && req.method === 'POST') {
            let body = ''
            req.on('data', (chunk) => {
              body += chunk
            })
            req.on('end', () => {
              try {
                const parsed = JSON.parse(body)
                const targetPath = path.resolve(process.cwd(), 'src/data/nativeAssets.json')
                fs.writeFileSync(targetPath, JSON.stringify(parsed, null, 2), 'utf-8')
                console.log('[DiskMiddleware] Saved nativeAssets.json to disk successfully')
                res.setHeader('Content-Type', 'application/json')
                res.statusCode = 200
                res.end(JSON.stringify({ success: true }))
              } catch (e) {
                console.error('[DiskMiddleware] Error saving nativeAssets.json:', e)
                res.statusCode = 500
                res.end(JSON.stringify({ error: String(e) }))
              }
            })
            return
          }
          if (req.url === '/api/save-native-spaces' && req.method === 'POST') {
            let body = ''
            req.on('data', (chunk) => {
              body += chunk
            })
            req.on('end', () => {
              try {
                const parsed = JSON.parse(body)
                const targetPath = path.resolve(process.cwd(), 'src/data/nativeSpaces.json')
                fs.writeFileSync(targetPath, JSON.stringify(parsed, null, 2), 'utf-8')
                console.log('[DiskMiddleware] Saved nativeSpaces.json to disk successfully')
                res.setHeader('Content-Type', 'application/json')
                res.statusCode = 200
                res.end(JSON.stringify({ success: true }))
              } catch (e) {
                console.error('[DiskMiddleware] Error saving nativeSpaces.json:', e)
                res.statusCode = 500
                res.end(JSON.stringify({ error: String(e) }))
              }
            })
            return
          }
          next()
        })
      },
    },
  ],
  resolve: {
    alias: {
      '@': path.resolve(__dirname, './src'),
    },
  },
  optimizeDeps: {
    // The RNNoise package ships a hand-rolled Emscripten loader that resolves
    // the .wasm via fetch(); pre-bundling it confuses that path.
    exclude: ['@jitsi/rnnoise-wasm'],
  },
  assetsInclude: ['**/*.wasm'],
  build: {
    chunkSizeWarningLimit: 6000,
  },
  server: {
    port: 5173,
    host: true,
    watch: {
      // Data files written at runtime by the Electron main process via IPC
      // (saveNativeAssets/saveNativeSpaces). They are imported as JSON modules,
      // so any change triggers a FULL page reload — recreating the camera at
      // the spawn point and teleporting the view to the top of the map on
      // every editor save. Runtime data also lives in localStorage, so
      // skipping the watch here has no functional downside in dev.
      ignored: [
        '**/src/data/nativeAssets.json',
        '**/src/data/nativeSpaces.json',
        '**/public/assets/**',
      ],
    },
  },
})
