import { afterEach, describe, expect, it, vi } from 'vitest'
import { createSpotifySearchSession } from '../../services/spotifySearchSession'

afterEach(() => vi.useRealTimers())
describe('Spotify suggestions while typing', () => {
  it('debounces typing and never displays the response to an older query', async () => {
    vi.useFakeTimers()
    let completeFirst!: (value: any) => void
    const search = vi.fn().mockImplementationOnce(() => new Promise(resolve => { completeFirst = resolve }))
      .mockResolvedValue({ ok: true, tracks: [{ id: 'new', title: 'Atual' }] })
    const changed = vi.fn()
    const session = createSpotifySearchSession(search, changed)
    session.setQuery('q')
    await vi.advanceTimersByTimeAsync(400)
    expect(search).not.toHaveBeenCalled()
    session.setQuery('qu')
    session.setQuery('queen')
    await vi.advanceTimersByTimeAsync(349)
    expect(search).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(1)
    expect(search).toHaveBeenCalledExactlyOnceWith('queen')
    session.setQuery('abba')
    await vi.advanceTimersByTimeAsync(350)
    expect(changed.mock.calls.at(-1)![0]).toMatchObject({ query: 'abba', loading: false, tracks: [{ id: 'new' }] })
    completeFirst({ ok: true, tracks: [{ id: 'old' }] })
    await Promise.resolve()
    expect(changed.mock.calls.at(-1)![0].query).toBe('abba')
    session.dispose()
  })
  it('clears results and cancels pending updates when the input is cleared or the panel closes', async () => {
    vi.useFakeTimers()
    const search = vi.fn(async () => ({ ok: true, tracks: [] }))
    const changed = vi.fn()
    const session = createSpotifySearchSession(search, changed)
    session.setQuery('queen')
    session.setQuery('')
    await vi.advanceTimersByTimeAsync(1000)
    expect(search).not.toHaveBeenCalled()
    expect(changed.mock.calls.at(-1)![0]).toMatchObject({ tracks: [], loading: false })
    session.setQuery('abba')
    session.dispose()
    await vi.advanceTimersByTimeAsync(1000)
    expect(search).not.toHaveBeenCalled()
  })
})
